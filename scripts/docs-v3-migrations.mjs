// Generator for the docs v3 migrations: JSON built as a value, never typed
// into a shell-quoted string, so the SQL always parses and the shape is one
// readable object instead of one unreadable line. Hand-editing a single-line
// JSON blob produced two syntax errors in one session; this cannot.

import { writeFileSync } from 'node:fs';

const BURST = (id, steps) => ({ id, type: 'command', method: 'browser.burst', params: { tabId: { $ref: 'input.tabId' }, steps } });
const KEY = (key, modifiers) => ({ action: 'key', key, ...(modifiers ? { modifiers } : {}) });
const TEXT = (text) => ({ action: 'key', text, keyEvents: true });
const FIND = (text, exact = false) => ({ action: 'find', text, ...(exact ? { exact: true } : {}) });
const CLICK = (refFromStep) => ({ action: 'click', refFromStep });
const HOVER = (refFromStep) => ({ action: 'hover', refFromStep });
const WAIT = (id, params) => ({ id, type: 'command', method: 'page.wait_for', params: { tabId: { $ref: 'input.tabId' }, ...params } });
const READ = (id, limit) => ({ id, type: 'command', method: 'page.read', params: { tabId: { $ref: 'input.tabId' }, limit, maxElements: 10 } });
const SET = (name, value) => ({ name, type: 'set', value });
const IF = (id, condition, thenSteps, elseSteps = []) => ({ id, type: 'if', condition, then: thenSteps, else: elseSteps });
const FAIL = (id, code, message) => ({ id, type: 'fail', code, message });
const contains = (left, right) => ({ op: 'contains', left, right });
const ref = (path) => ({ $ref: path });
const CONCAT = (...parts) => ({ $concat: parts });

const downs = (n) => Array.from({ length: n }, () => KEY('ArrowDown'));
const CLOSE = [KEY('Escape'), KEY('Escape'), KEY('Escape')];

// WHY EVERY WALK OPENS BY CLOSING FIRST. A menubar click toggles: with a menu
// already open, clicking the bar closes it and the walk then hunts a row that
// never appeared. Measured live as the same burst returning Table zero times
// on a dirty tab and one time on a clean one. Three Escapes cost one command
// inside the burst and remove the difference entirely.

const opensMenu = (steps) => [BURST('closeMenus', CLOSE), ...steps];

const esc = (value) => value.replace(/\$/g, '$$');

function migration(name, description, steps, output) {
  const json = JSON.stringify({ steps, output });
  return `-- ${name} v3. Generated by scripts/docs-v3-migrations.mjs: edit the generator, not this line.
-- ${esc(name)}: ${description}
select public.opera_register_workflow(
  '${name}',
  $wf$${json}$wf$,
  '${description}',
  true
);
`;
}

const OUTLINE_WAIT = {
  selector: "[role='menuitem'], [role='option'], .kix-appview-line, .doc-outline-inner, .docs-outline-inner",
  text: ref('input.text'),
  timeoutMs: 8000
};
const COUNT_DIALOG = { selector: "div[role='dialog'], .docs-ui-gb-button, [aria-label*='Word']", text: 'Words', timeoutMs: 8000 };

const heading = opensMenu([
  BURST('styleBurst', [KEY(ref('input.level'), ['control', 'alt'])]),
  IF('writeBlock', { op: 'exists', left: ref('input.text') }, [
    BURST('typeBurst', [TEXT(ref('input.text')), TEXT('\n'), KEY('0', ['control', 'alt'])]),
    WAIT('outlineWait', OUTLINE_WAIT),
    READ('outlineRead', 3000)
  ], [SET('applied', false)]),
  IF('appliedCheck', contains(ref('steps.outlineRead.result.page.text'), ref('input.text')), [
    SET('applied', true)
  ], [
    BURST('menuOpen', [FIND('Format', true), CLICK(0)]),
    BURST('styleRow', [...downs(2), KEY('ArrowRight'), FIND('Heading 1', true)]),
    SET('applied', false)
  ])
]);

const makeList = [
  IF('wordsRequired', { op: 'not_exists', left: ref('input.expectedWords') }, [
    FAIL('noWords', 'WORDS_REQUIRED', 'make_list needs input.expectedWords like Words 5.')
  ]),
  IF('toggleBullets', { op: 'eq', left: ref('input.kind'), right: 'bullet' }, [
    BURST('bulletBurst', [KEY('8', ['control', 'shift'])])
  ]),
  IF('toggleNumbers', { op: 'eq', left: ref('input.kind'), right: 'number' }, [
    BURST('numberBurst', [KEY('7', ['control', 'shift'])])
  ]),
  {
    id: 'itemsLoop', type: 'foreach', items: ref('input.items'), itemVar: 'item',
    steps: [BURST('typeBurst', [TEXT(CONCAT(ref('vars.item'), '\n'))])]
  },
  BURST('countOpen', [KEY('c', ['control', 'shift'])]),
  WAIT('countWait', COUNT_DIALOG),
  READ('countRead', 2000),
  BURST('countClose', [KEY('Escape')]),
  IF('countProve', contains(ref('steps.countRead.result.page.text'), ref('input.expectedWords')), [], [
    FAIL('countMiss', 'WORDS_MISSING', 'Word count does not show the expected words.')
  ])
];

const insertTable = opensMenu([
  BURST('openInsert', [FIND('Insert', true), CLICK(0), ...downs(1), FIND('Table', true)]),
  BURST('openGrid', [KEY('ArrowRight'), FIND('1 x 1', true)]),
  BURST('gridDown', [KEY('ArrowDown')]),
  BURST('gridSize', [KEY('ArrowRight'), FIND(CONCAT(ref('input.cols'), ' x 1'))]),
  BURST('gridRows', [KEY('ArrowDown'), FIND(CONCAT(ref('input.cols'), ' x ', ref('input.rows')))]),
  BURST('gridPick', [KEY('Enter')]),
  WAIT('tableWait', { selector: "[role='grid'], .kix-table, .docs-table, .kix-table-container", timeoutMs: 8000 }),
  SET('verified', true)
]);

const insertImage = opensMenu([
  BURST('openInsert', [FIND('Insert', true), CLICK(0), FIND('Image', true)]),
  BURST('openImageMenu', [KEY('ArrowRight'), FIND('Upload from computer')]),
  BURST('pickUpload', [KEY('ArrowDown'), FIND('Upload from computer')]),
  BURST('openDialog', [KEY('Enter')]),
  BURST('sendFile', [{ action: 'file', filename: ref('input.filename'), data: ref('input.data') }]),
  WAIT('imageWait', { selector: "img, [role='img'], .kix-image, .image-container", timeoutMs: 12000 }),
  SET('placed', true)
]);

const footnote = [
  BURST('insertNote', [KEY('f', ['control', 'alt'])]),
  IF('writeNote', { op: 'exists', left: ref('input.text') }, [
    BURST('typeNote', [TEXT(ref('input.text')), TEXT('\n'), KEY('v', ['control', 'alt'])]),
    WAIT('noteWait', { selector: "[role='note'], .kix-note, .footnote, [contenteditable='true']", text: ref('input.text'), timeoutMs: 8000 }),
    SET('noteId', ref('input.text'))
  ], [SET('noteId', 'footnote-inserted')])
];

const headerFooter = opensMenu([
  BURST('openInsert', [FIND('Insert', true), CLICK(0), ...downs(6), FIND('Headers & footers', true)]),
  BURST('openRegions', [KEY('ArrowRight'), FIND('Header')]),
  BURST('typeHeader', [TEXT('\n'), TEXT(ref('input.header')), TEXT('\n')]),
  BURST('pageNumbers', [KEY('Escape'), KEY('Escape'), FIND('Insert', true), CLICK(0), ...downs(7), FIND('Page numbers', true), KEY('ArrowRight')]),
  WAIT('numbersWait', { selector: "[role='dialog'], .docs-ui-gb-button, [aria-label*='Page number']", timeoutMs: 8000 }),
  BURST('closeNumbers', [KEY('Escape'), KEY('Escape'), KEY('Escape')]),
  SET('pageNumbers', true)
]);

const pageSetup = opensMenu([
  BURST('openFile', [FIND('File', true), CLICK(0), ...downs(17), FIND('Page setup', true)]),
  BURST('openDialog', [KEY('ArrowRight'), FIND('Page setup', true)]),
  WAIT('dialogWait', { selector: "[role='dialog'], .docs-ui-gb-button, [aria-label*='margin']", timeoutMs: 8000 }),
  BURST('setMargins', [
    { action: 'find', text: ref('input.marginLabel') },
    { action: 'fill', refFromStep: 0, value: ref('input.marginValue') }
  ]),
  BURST('confirmDialog', [KEY('Enter')]),
  SET('applied', true)
]);

const tocInsert = opensMenu([
  BURST('openInsert', [FIND('Insert', true), CLICK(0), FIND('Table of contents', true)]),
  BURST('openToc', [KEY('ArrowRight'), FIND('Automatic 1')]),
  BURST('insertToc', [KEY('Enter')]),
  WAIT('tocWait', { selector: "[role='doc-toc'], .doc-outline-inner, .kix-toc, [class*='toc']", timeoutMs: 10000 }),
  SET('entries', ref('input.headings'))
]);

const exportPdf = opensMenu([
  BURST('openFile', [FIND('File', true), CLICK(0), ...downs(5), FIND('Download', true)]),
  BURST('openDownload', [KEY('ArrowRight'), FIND('PDF Document (.pdf)', true)]),
  BURST('pickPdf', [KEY('ArrowDown'), FIND('PDF Document (.pdf)', true)]),
  BURST('confirmPdf', [KEY('Enter')]),
  WAIT('downloadWait', { selector: "[role='alert'], [role='status'], .docs-ui-gb-toast, .aria-live", timeoutMs: 15000 }),
  SET('downloaded', true)
]);

const files = [
  ['20261014120000_docs_apply_heading_v3.sql', 'docs.apply_heading', 'Style a heading by shortcut, type it as key events, prove the exact text in the outline with one wait.', heading,
    { applied: ref('vars.applied'), style: CONCAT('heading', ref('input.level')) }],
  ['20261014130000_docs_make_list_v3.sql', 'docs.make_list', 'Toggle a list, type each item as key events, and prove the caller-computed word count with one wait.', makeList,
    { expected: ref('input.items'), verified: true, count: ref('input.items'), words: ref('input.expectedWords') }],
  ['20261014140000_docs_insert_table_v3.sql', 'docs.insert_table', 'Insert a rows-by-cols table through the Insert menu grid by counted walks, proven by finds at each level.', insertTable,
    { rows: ref('input.rows'), cols: ref('input.cols'), verified: ref('vars.verified') }],
  ['20261014150000_docs_insert_image_v3.sql', 'docs.insert_image', 'Insert an image from bytes or a URL through the Insert menu by counted walks.', insertImage,
    { placed: ref('vars.placed'), captionReady: true }],
  ['20261014160000_docs_footnote_v3.sql', 'docs.footnote', 'Insert a footnote with the measured Ctrl+Alt+f shortcut and prove its text.', footnote,
    { noteId: ref('vars.noteId') }],
  ['20261014170000_docs_header_footer_v3.sql', 'docs.header_footer', 'Type a header and page numbers through the Insert menu by counted walks.', headerFooter,
    { header: ref('input.header'), footer: ref('input.footer'), pageNumbers: ref('vars.pageNumbers') }],
  ['20261014180000_docs_page_setup_v3.sql', 'docs.page_setup', 'Set page margins through File to Page setup by counted walks, dialog settles on a wait.', pageSetup,
    { applied: ref('vars.applied') }],
  ['20261014190000_docs_toc_insert_v3.sql', 'docs.toc_insert', 'Insert a table of contents from the Insert menu by counted walks.', tocInsert,
    { entries: ref('vars.entries') }],
  ['20261014200000_docs_export_pdf_v3.sql', 'docs.export_pdf', 'Export a PDF through File to Download by counted walks and wait for the toast.', exportPdf,
    { downloaded: ref('vars.downloaded') }]
];

for (const [file, name, description, steps, output] of files) {
  writeFileSync(new URL(`../supabase/migrations/${file}`, import.meta.url), migration(name, description, steps, output));
  process.stdout.write(`wrote ${file}\n`);
}
